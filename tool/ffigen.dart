// ignore_for_file: experimental_member_use
import 'dart:io';
import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  for (final bundled in [false, true]) {
    await FfiGenerator(
      input: Input(entryPoints: [root.resolve('native/quickjs/session.h')]),
      visitors: [
        Visitor(
          func: (node) {
            node.isIncluded = {
              'ForceSniffQuickJsExecute',
              'ForceSniffQuickJsRuntimeManifestJSON',
              'ForceSniffQuickJsSessionCreate',
              'ForceSniffQuickJsSessionEval',
              'ForceSniffQuickJsSessionDestroy',
              'ForceSniffQuickJsFree',
            }.contains(node.originalName);
            node.recordUse = bundled && node.isIncluded;
          },
        ),
      ],
      output: Output(
        dart: DartOutput(
          path: root.resolve(
            bundled
                ? 'lib/src/third_party/session_native.g.dart'
                : 'lib/src/third_party/session.g.dart',
          ),
        ),
        style: bundled
            ? const NativeExternalBindings(
                assetId:
                    'package:script_engine/src/third_party/session_native.g.dart',
              )
            : const DynamicLibraryBindings(
                wrapperName: 'QuickJsSessionBindings',
              ),
        recordUseMapping: bundled
            ? root.resolve(
                'lib/src/third_party/session.record_use_mapping.g.dart',
              )
            : null,
        preamble:
            '// Generated by package:ffigen. Do not edit manually.\n// ignore_for_file: type=lint\n',
      ),
    ).generate();
  }
}
